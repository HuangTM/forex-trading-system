#!/usr/bin/env python3
"""Download historical central bank rate data from FRED and save as Parquet.

Produces data/rates/rate_differentials.parquet (reference-period dates, for
swap costs) and data/rates/rate_differentials_pit.parquet (dated by publication,
for signals), each with 12 columns, one per supported pair: EURUSD_diff, USDJPY_diff, GBPUSD_diff, EURJPY_diff,
GBPJPY_diff, EURGBP_diff, AUDUSD_diff, NZDUSD_diff, USDCAD_diff,
AUDJPY_diff, NZDJPY_diff, CADJPY_diff.

These differentials are used by CarryStrategy for dynamic signal generation.

Rewritten 2026-08-17:
  * JPY was previously INTDSRJPM193N (annual, FROZEN at 2017-04 = 0.3 on disk).
    Now IRSTCI01JPM156N (monthly uncollateralized overnight call rate), which
    captures the NIRP era (negative from 2016-02) and the 2024-2026 hikes
    (current through 2026-06 at fetch time).
  * Added AUD / NZD / CAD (IR3TIB01xxM156N 3-month interbank) so all 12
    pair differentials are generated by THIS script — the previous on-disk
    12-column file had no in-repo generator (provenance hole).
  * Uses the public fredgraph.csv endpoint — NO API key required.

Usage:
    python scripts/download_fred_rates.py
"""

from __future__ import annotations

import argparse
import io
import urllib.request
from pathlib import Path

import pandas as pd

# FRED series IDs (all monthly, percent per annum, fetched via fredgraph.csv)
SERIES = {
    "USD": "FEDFUNDS",          # Effective Federal Funds Rate (monthly avg)
    "EUR": "ECBMRRFR",          # ECB Main Refinancing Rate (daily)
    "JPY": "IRSTCI01JPM156N",   # Japan uncollateralized overnight call rate (monthly)
    "AUD": "IR3TIB01AUM156N",   # Australia 3-month interbank rate (monthly)
    "NZD": "IR3TIB01NZM156N",   # New Zealand 3-month interbank rate (monthly)
    "CAD": "IR3TIB01CAM156N",   # Canada 3-month interbank rate (monthly)
}

# Publication lag, in whole months after the reference month's FIRST day, before a
# monthly observation (FRED-dated M-01) is reliably public. Used only for the
# point-in-time table that feeds SIGNALS; the reference-period table (used to
# accrue swap COSTS, where the month's actual rate is what gets charged) is unlagged.
# Measured 2026-10-28 against fredgraph.csv: FEDFUNDS had 2026-09 (daily EFFR is
# public, so the month's mean is known at month end -> M+1); JPY/NZD/CAD had 2026-09
# but are not guaranteed before M+2; AUD had only 2026-08 -> M+3. One snapshot, so
# the values lean conservative. EUR (daily) and GBP (decision dates) are lag 0.
PUBLICATION_LAG_MONTHS = {"USD": 1, "JPY": 2, "NZD": 2, "CAD": 2, "AUD": 3, "EUR": 0, "GBP": 0}

# 12 pairs as (base, quote); diff = (base_rate - quote_rate) / 100.
PAIRS = [
    ("EURUSD", "EUR", "USD"), ("USDJPY", "USD", "JPY"), ("GBPUSD", "GBP", "USD"),
    ("EURJPY", "EUR", "JPY"), ("GBPJPY", "GBP", "JPY"), ("EURGBP", "EUR", "GBP"),
    ("AUDUSD", "AUD", "USD"), ("NZDUSD", "NZD", "USD"), ("USDCAD", "USD", "CAD"),
    ("AUDJPY", "AUD", "JPY"), ("NZDJPY", "NZD", "JPY"), ("CADJPY", "CAD", "JPY"),
]

# BOE historical rates: FRED coverage is incomplete, so we provide a manual
# time series of key BOE rate changes. This covers major moves since 2000.
# Source: https://www.bankofengland.co.uk/boeapps/database/Bank-Rate.asp
BOE_MANUAL = [
    ("2000-01-01", 5.50), ("2001-02-08", 5.75), ("2001-04-05", 5.50),
    ("2001-05-10", 5.25), ("2001-08-02", 5.00), ("2001-09-18", 4.75),
    ("2001-10-04", 4.50), ("2001-11-08", 4.00), ("2003-02-06", 3.75),
    ("2003-07-10", 3.50), ("2003-11-06", 3.75), ("2004-02-05", 4.00),
    ("2004-06-10", 4.50), ("2004-08-05", 4.75), ("2005-08-04", 4.50),
    ("2006-08-03", 4.75), ("2006-11-09", 5.00), ("2007-01-11", 5.25),
    ("2007-07-05", 5.75), ("2007-12-06", 5.50), ("2008-02-07", 5.25),
    ("2008-04-10", 5.00), ("2008-10-08", 4.50), ("2008-11-06", 3.00),
    ("2008-12-04", 2.00), ("2009-01-08", 1.50), ("2009-02-05", 1.00),
    ("2009-03-05", 0.50), ("2016-08-04", 0.25), ("2017-11-02", 0.50),
    ("2018-08-02", 0.75), ("2020-03-11", 0.25), ("2020-03-19", 0.10),
    ("2021-12-16", 0.25), ("2022-02-03", 0.50), ("2022-03-17", 0.75),
    ("2022-05-05", 1.00), ("2022-06-16", 1.25), ("2022-08-04", 1.75),
    ("2022-09-22", 2.25), ("2022-11-03", 3.00), ("2022-12-15", 3.50),
    ("2023-02-02", 4.00), ("2023-03-23", 4.25), ("2023-05-11", 4.50),
    ("2023-06-22", 5.00), ("2023-08-03", 5.25), ("2024-08-01", 5.00),
    ("2024-11-07", 4.75), ("2025-02-06", 4.50), ("2025-05-08", 4.25),
    ("2025-08-07", 4.00), ("2025-11-06", 3.75),
]

# ECBMRRFR is the FIXED-rate-tender MRO rate. From 2000-06-28 to 2008-10-14 the
# ECB ran VARIABLE-rate tenders with a minimum bid rate, so ECBMRRFR carries no
# changes in that window and a plain ffill froze EUR at 4.25% for 8.5 years
# (found 2026-10-25). Inside the window the minimum bid rate sat at the midpoint
# of the deposit / marginal-lending corridor (symmetric +/-100bp), so EUR is
# filled with (ECBDFR + ECBMLFR) / 2 there. Checked against ECBMRRFR where both
# exist: max |diff| 0.000 on 2008-10-15..2012-12-31.
ECB_CORRIDOR = ("ECBDFR", "ECBMLFR")
ECB_VARIABLE_TENDER = ("2000-06-28", "2008-10-14")

OUTPUT_DIR = Path("data/rates")
_FREDGRAPH_URL = "https://fred.stlouisfed.org/graph/fredgraph.csv?id={series_id}"


def download_fred_series(series_id: str, start: str = "2000-01-01") -> pd.Series:
    """Download a FRED series via the public fredgraph.csv endpoint (no API key).

    FRED's official API requires a key; the fredgraph.csv endpoint is the same
    data served for chart downloads and is public. Values are percent p.a.
    """
    url = _FREDGRAPH_URL.format(series_id=series_id)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        raw = resp.read()
    df = pd.read_csv(io.BytesIO(raw))
    df.columns = ["date", "value"]
    df["value"] = pd.to_numeric(df["value"], errors="coerce")
    df["date"] = pd.to_datetime(df["date"])
    s = pd.Series(df["value"].values, index=pd.DatetimeIndex(df["date"], name="date"))
    s = s.dropna()
    s = s[s.index >= pd.Timestamp(start)]
    return s


def fill_ecb_variable_tender_gap(mro: pd.Series, dfr: pd.Series, mlf: pd.Series) -> pd.Series:
    """Replace EUR inside ECB_VARIABLE_TENDER with the corridor midpoint (see note above)."""
    start, end = (pd.Timestamp(d) for d in ECB_VARIABLE_TENDER)
    midpoint = ((dfr + mlf) / 2.0).dropna()
    inside = midpoint[(midpoint.index >= start) & (midpoint.index <= end)]
    outside = mro[(mro.index < start) | (mro.index > end)]
    return pd.concat([outside, inside]).sort_index().rename(mro.name)


def load_raw_series(currency: str) -> pd.Series:
    """Read a series previously saved by main() to data/rates/raw/{currency}.csv."""
    df = pd.read_csv(OUTPUT_DIR / "raw" / f"{currency}.csv")
    return pd.Series(df.iloc[:, 1].to_numpy(), index=pd.DatetimeIndex(df.iloc[:, 0], name="date"))


def build_boe_series() -> pd.Series:
    """Build BOE rate series from manual data."""
    dates = [pd.Timestamp(d) for d, _ in BOE_MANUAL]
    rates = [r for _, r in BOE_MANUAL]
    return pd.Series(rates, index=dates, name="GBP")


def to_point_in_time(
    rates: dict[str, pd.Series], lag_months: dict[str, int] = PUBLICATION_LAG_MONTHS
) -> dict[str, pd.Series]:
    """Re-date each series to when its value was public (signal-safe view).

    A monthly observation dated M-01 is moved to the first day of month M+lag.
    Series with lag 0 are returned unchanged.
    """
    out = {}
    for currency, series in rates.items():
        lag = lag_months[currency]
        if lag:
            series = series.copy()
            series.index = series.index.to_period("M").to_timestamp() + pd.DateOffset(months=lag)
        out[currency] = series
    return out


def build_rate_differentials(rates: dict[str, pd.Series]) -> pd.DataFrame:
    """Merge rate series and compute all 12 pair differentials.

    Returns DataFrame indexed by date with columns {PAIR}_diff =
    (base_rate - quote_rate) / 100, i.e. the annualized carry of a LONG
    position in the pair, in decimal.

    Dates are the series' own dates. Pass ``to_point_in_time(rates)`` to get
    the publication-lagged table for signal generation.
    """
    # Create a common daily date range
    all_dates = set()
    for s in rates.values():
        all_dates.update(s.index)
    date_range = pd.date_range(min(all_dates), max(all_dates), freq="B")  # Business days

    # Reindex each series to business days and forward-fill. FRED dates monthly
    # series at the FIRST of the reference month, so on the unlagged input the
    # table states month M's rate from M-01: right for accruing that month's swap
    # cost, a lookahead for signals (2026-08-17 audit). Signals use the
    # point-in-time table built from to_point_in_time(rates).
    aligned = pd.DataFrame(index=date_range)
    aligned.index.name = "date"
    for currency, series in rates.items():
        aligned[currency] = series.reindex(date_range).ffill()

    # Compute differentials (base rate - quote rate for long position)
    result = pd.DataFrame(index=aligned.index)
    result.index.name = "date"
    for pair, base, quote in PAIRS:
        result[f"{pair}_diff"] = (aligned[base] - aligned[quote]) / 100.0  # % to decimal

    return result.dropna()


def main():
    parser = argparse.ArgumentParser(description="Download FRED rate data for carry strategy")
    parser.add_argument("--start", default="2000-01-01", help="Start date for data download")
    parser.add_argument("--from-raw", action="store_true",
                        help="Rebuild from data/rates/raw/*.csv instead of re-downloading "
                             "(only the ECB corridor series are fetched, to fill the EUR gap)")
    args = parser.parse_args()

    rates = {}

    if args.from_raw:
        for currency in [*SERIES, "GBP"]:
            rates[currency] = load_raw_series(currency)
            print(f"Loaded raw {currency}: {len(rates[currency])} observations")
    else:
        # Download from FRED (public fredgraph.csv endpoint, no API key)
        for currency, series_id in SERIES.items():
            print(f"Downloading {currency} ({series_id})...")
            rates[currency] = download_fred_series(series_id, args.start)
            print(f"  Got {len(rates[currency])} observations: "
                  f"{rates[currency].index[0].date()} to {rates[currency].index[-1].date()}")

        # Add BOE manual series
        print("Building GBP series from manual BOE data...")
        rates["GBP"] = build_boe_series()
        print(f"  {len(rates['GBP'])} rate changes")

    print(f"Filling EUR variable-rate-tender gap {ECB_VARIABLE_TENDER} from {ECB_CORRIDOR}...")
    dfr, mlf = (download_fred_series(s, args.start) for s in ECB_CORRIDOR)
    rates["EUR"] = fill_ecb_variable_tender_gap(rates["EUR"], dfr, mlf)

    # Save individual series
    raw_dir = OUTPUT_DIR / "raw"
    raw_dir.mkdir(parents=True, exist_ok=True)
    for currency, series in rates.items():
        path = raw_dir / f"{currency}.csv"
        series.to_csv(path, header=True)
        print(f"  Saved {path}")

    # Build and save differentials
    print("Computing rate differentials...")
    diffs = build_rate_differentials(rates)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    output_path = OUTPUT_DIR / "rate_differentials.parquet"
    diffs.to_parquet(output_path)
    print(f"Saved {output_path} ({len(diffs)} rows, "
          f"{diffs.index[0].date()} to {diffs.index[-1].date()}, {len(diffs.columns)} pairs)")

    pit = build_rate_differentials(to_point_in_time(rates))
    pit_path = OUTPUT_DIR / "rate_differentials_pit.parquet"
    pit.to_parquet(pit_path)
    print(f"Saved {pit_path} (point-in-time, for signals; {len(pit)} rows, "
          f"{pit.index[0].date()} to {pit.index[-1].date()})")

    # Summary
    print("\n=== Latest Differentials ===")
    latest = diffs.iloc[-1]
    for col in diffs.columns:
        pair = col.replace("_diff", "")
        print(f"  {pair}: {latest[col]:+.4f} ({latest[col]*100:+.2f}%)")


if __name__ == "__main__":
    main()
